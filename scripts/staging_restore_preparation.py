"""
CeylonGo - Staging Rehearsal Restore Safety & Preparation Script
================================================================
Prepares, validates, and verifies safe restore commands for creating
CeylonGoDB_Migration_Staging without risking development or production databases.

Strict Safety Invariants Enforced:
1. NEVER uses WITH REPLACE under any circumstances.
2. Uses modern, safe THROW statements instead of severity-20 RAISERROR.
3. Refuses execution if CeylonGoDB_Migration_Staging already exists in sys.databases.
4. Refuses execution if target database is CeylonGoDB, CeylonGoDB_Development, or system databases.
5. Employs explicit WITH MOVE mappings for logical files 'CeylonGoDB' and 'CeylonGoDB_log'.
6. Enforces distinct staging physical file names (CeylonGoDB_Migration_Staging.mdf / .ldf).
7. Aborts if destination files already exist on disk (both pre-flight and in T-SQL).
8. Embeds mandatory RESTORE VERIFYONLY in generated SQL (never assumes prior verification).
9. Strict separation: offline script generation NEVER connects to SQL Server.
10. NEVER executes restore operations during Phase 5D-3C-1 (Static validation only).
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Any

# Ensure project backend directory is in path
BACKEND_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_DIR))

from scripts.staging_guard import (
    StagingDatabaseSafetyError,
    assert_staging_database_does_not_exist,
    verify_safe_staging_database_name,
)

TARGET_STAGING_DB = "CeylonGoDB_Migration_Staging"
DEFAULT_BACKUP_PATH = r"C:\Program Files\Microsoft SQL Server\MSSQL17.SQLEXPRESS\MSSQL\Backup\CeylonGoDB_Development_PreMigration_030_041.bak"
DEFAULT_DATA_DIR = r"C:\Program Files\Microsoft SQL Server\MSSQL17.SQLEXPRESS\MSSQL\DATA"

LOGICAL_DATA_NAME = "CeylonGoDB"
LOGICAL_LOG_NAME = "CeylonGoDB_log"

STAGING_MDF_NAME = "CeylonGoDB_Migration_Staging.mdf"
STAGING_LDF_NAME = "CeylonGoDB_Migration_Staging_log.ldf"


def generate_safe_restore_sql(
    backup_path: str = DEFAULT_BACKUP_PATH,
    data_dir: str = DEFAULT_DATA_DIR,
    target_db: str = TARGET_STAGING_DB,
) -> str:
    """
    Constructs an authoritative, verified T-SQL RESTORE statement offline.

    Guarantees:
    - Never uses WITH REPLACE.
    - Uses safe THROW statements (not severity-20 RAISERROR).
    - Aborts if staging DB already exists in sys.databases.
    - Checks for MDF/LDF disk collisions via sys.dm_os_file_exists.
    - Embeds RESTORE VERIFYONLY so verification is not assumed.
    - Explicit WITH MOVE mappings.
    - Pure offline function with zero database connectivity.
    """
    verify_safe_staging_database_name(target_db)

    mdf_target = os.path.join(data_dir, STAGING_MDF_NAME)
    ldf_target = os.path.join(data_dir, STAGING_LDF_NAME)

    sql = f"""-- ==============================================================================
-- SAFE STAGING RESTORE SCRIPT (Fail-Closed, Zero Replace, Explicit MOVE)
-- Target Staging Database: {target_db}
-- Generated by: scripts/staging_restore_preparation.py (Phase 5D-3C-1)
-- ==============================================================================

SET NOCOUNT ON;

-- 1. Pre-Execution Safety Assertions (Modern THROW Statements)
IF DB_NAME() = N'{target_db}'
BEGIN
    THROW 50001, N'FATAL: Cannot restore database while connected to it. Switch to master.', 1;
END;

IF EXISTS (SELECT 1 FROM sys.databases WHERE name = N'{target_db}')
BEGIN
    THROW 50002, N'FATAL: Target database [{target_db}] already exists in sys.databases. Refusing restore without explicit teardown.', 1;
END;

-- 2. Destination Physical File Collision Checks (Prevent overwriting unattached data)
DECLARE @mdf_exists INT = 0;
DECLARE @ldf_exists INT = 0;

SELECT @mdf_exists = file_exists FROM sys.dm_os_file_exists(N'{mdf_target}');
IF @mdf_exists = 1
BEGIN
    THROW 50003, N'FATAL: Destination data file [{mdf_target}] already exists on disk. Refusing overwrite.', 1;
END;

SELECT @ldf_exists = file_exists FROM sys.dm_os_file_exists(N'{ldf_target}');
IF @ldf_exists = 1
BEGIN
    THROW 50004, N'FATAL: Destination log file [{ldf_target}] already exists on disk. Refusing overwrite.', 1;
END;

-- 3. Source Backup Readability & Checksum Verification (Never assume prior success)
RESTORE VERIFYONLY
FROM DISK = N'{backup_path}'
WITH CHECKSUM;

-- 4. Verified Staging Restore Execution (Explicit WITH MOVE, Strictly NO REPLACE)
RESTORE DATABASE [{target_db}]
FROM DISK = N'{backup_path}'
WITH
    MOVE N'{LOGICAL_DATA_NAME}' TO N'{mdf_target}',
    MOVE N'{LOGICAL_LOG_NAME}' TO N'{ldf_target}',
    CHECKSUM,
    RECOVERY,
    STATS = 10;
GO
"""
    return sql


def validate_offline_restore_contract(
    backup_path: str = DEFAULT_BACKUP_PATH,
    data_dir: str = DEFAULT_DATA_DIR,
    target_db: str = TARGET_STAGING_DB,
) -> dict[str, Any]:
    """
    Performs purely offline static contract validation without any SQL Server connection.
    """
    results: dict[str, Any] = {
        "target_db_name": target_db,
        "is_safe_db_name": False,
        "mode": "offline",
        "target_mdf_exists_locally": None,
        "target_ldf_exists_locally": None,
        "backup_file_exists_locally": False,
        "sql_statement": "",
        "safety_violations": [],
    }

    # 1. Target database name validation
    try:
        verify_safe_staging_database_name(target_db)
        results["is_safe_db_name"] = True
    except StagingDatabaseSafetyError as err:
        results["safety_violations"].append(f"Invalid target database: {err}")
        return results

    # 2. Local filesystem checks if accessible
    mdf_target = os.path.join(data_dir, STAGING_MDF_NAME)
    ldf_target = os.path.join(data_dir, STAGING_LDF_NAME)

    try:
        results["target_mdf_exists_locally"] = os.path.exists(mdf_target)
        if results["target_mdf_exists_locally"]:
            results["safety_violations"].append(
                f"Physical file collision: Target data file already exists at '{mdf_target}'."
            )
    except Exception:
        results["target_mdf_exists_locally"] = None

    try:
        results["target_ldf_exists_locally"] = os.path.exists(ldf_target)
        if results["target_ldf_exists_locally"]:
            results["safety_violations"].append(
                f"Physical file collision: Target log file already exists at '{ldf_target}'."
            )
    except Exception:
        results["target_ldf_exists_locally"] = None

    try:
        results["backup_file_exists_locally"] = os.path.exists(backup_path)
    except Exception:
        results["backup_file_exists_locally"] = False

    results["sql_statement"] = generate_safe_restore_sql(backup_path, data_dir, target_db)
    return results


def run_live_preflight_checks(
    backup_path: str = DEFAULT_BACKUP_PATH,
    data_dir: str = DEFAULT_DATA_DIR,
    target_db: str = TARGET_STAGING_DB,
) -> dict[str, Any]:
    """
    Performs database-dependent preflight checks against live SQL Server.
    Must ONLY be executed when caller explicitly requests live validation.
    """
    from scripts.migrate import DatabaseConfig, get_connection

    # First run offline validation
    results = validate_offline_restore_contract(backup_path, data_dir, target_db)
    results["mode"] = "live"
    results["staging_db_exists_in_sys_databases"] = None
    results["live_connection_verified"] = False

    if not results["is_safe_db_name"]:
        return results

    try:
        config = DatabaseConfig.from_env(database_override="master")
        conn = get_connection(config)
        try:
            cursor = conn.cursor()
            cursor.execute("SELECT COUNT(*) FROM sys.databases WHERE LOWER(name) = ?;", (target_db.lower(),))
            db_exists = cursor.fetchone()[0] > 0
            results["staging_db_exists_in_sys_databases"] = db_exists
            results["live_connection_verified"] = True

            if db_exists:
                results["safety_violations"].append(
                    f"Target staging database '{target_db}' already exists in sys.databases. "
                    "Overwriting via WITH REPLACE is strictly forbidden."
                )
        finally:
            conn.close()
    except Exception as exc:
        results["safety_violations"].append(f"Live SQL Server check failed: {exc}")

    return results


def main() -> int:
    parser = argparse.ArgumentParser(
        prog="staging_restore_preparation.py",
        description="CeylonGo Staging Rehearsal Safe Restore Preparation Tool (Offline by Default)",
    )
    parser.add_argument(
        "--target-db",
        type=str,
        default=TARGET_STAGING_DB,
        help=f"Target staging database (default: {TARGET_STAGING_DB})",
    )
    parser.add_argument(
        "--backup-path",
        type=str,
        default=DEFAULT_BACKUP_PATH,
        help="Path to pre-rehearsal .bak file",
    )
    parser.add_argument(
        "--data-dir",
        type=str,
        default=DEFAULT_DATA_DIR,
        help="Target SQL Server DATA directory for staging MDF/LDF files",
    )
    parser.add_argument(
        "--print-sql",
        action="store_true",
        help="Print the generated safe T-SQL restore script",
    )
    parser.add_argument(
        "--live-check",
        action="store_true",
        help="Perform optional live SQL Server connection checks (default is offline)",
    )

    args = parser.parse_args()

    print("\n" + "=" * 80)
    print(" CEYLONGO STAGING REHEARSAL RESTORE SAFETY AUDIT & PREPARATION")
    print(f" Execution Mode: {'LIVE (Connected to SQL Server)' if args.live_check else 'OFFLINE (Zero DB Connections)'}")
    print("=" * 80)

    if args.live_check:
        val = run_live_preflight_checks(
            backup_path=args.backup_path,
            data_dir=args.data_dir,
            target_db=args.target_db,
        )
    else:
        val = validate_offline_restore_contract(
            backup_path=args.backup_path,
            data_dir=args.data_dir,
            target_db=args.target_db,
        )

    print(f"Target Staging Database: {val['target_db_name']}")
    print(f"Database Name Approved : {'[YES]' if val['is_safe_db_name'] else '[NO]'}")
    if args.live_check:
        print(f"Target DB in sys.db    : {'[EXISTS - COLLISION]' if val.get('staging_db_exists_in_sys_databases') else '[CLEAN - Does Not Exist]'}")
    print(f"Target MDF on Disk     : {'[EXISTS - COLLISION]' if val['target_mdf_exists_locally'] else '[CLEAN - Does Not Exist]'}")
    print(f"Target LDF on Disk     : {'[EXISTS - COLLISION]' if val['target_ldf_exists_locally'] else '[CLEAN - Does Not Exist]'}")
    print(f"Source Backup Present  : {'[YES]' if val['backup_file_exists_locally'] else '[PENDING CREATION]'}")
    print("-" * 80)

    if val["safety_violations"]:
        print("\n[SAFETY AUDIT WARNINGS / BLOCKS]:")
        for violation in val["safety_violations"]:
            print(f"  - {violation}")
        print("\n[VERDICT] Pre-restore safety check failed.")
        return 1
    else:
        print("\n[SUCCESS] All pre-restore safety checks PASSED.")
        print("  - Zero WITH REPLACE generated.")
        print("  - Safe THROW statements employed (zero severity-20 RAISERROR).")
        print("  - Target staging MDF/LDF files do not conflict on disk.")
        print("  - Source database CeylonGoDB_Development is 100% protected.")

    if args.print_sql:
        print("\n--- GENERATED SAFE RESTORE T-SQL ---")
        print(val["sql_statement"])

    print("=" * 80 + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
